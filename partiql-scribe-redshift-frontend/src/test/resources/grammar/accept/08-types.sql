-- Data types, in CAST, TRY_CAST, CONVERT, and the :: shorthand.
-- https://docs.aws.amazon.com/redshift/latest/dg/c_Supported_data_types.html

--#[cast]
SELECT CAST(a AS INT), CAST(b AS VARCHAR), CAST('1' AS BIGINT), CAST(NULL AS DATE) FROM t;

--#[try-cast]
SELECT TRY_CAST(a AS INT), TRY_CAST('x' AS DECIMAL(10, 2)) FROM t;

--#[convert]
SELECT CONVERT(INT, a), CONVERT(VARCHAR(10), b), CONVERT(DECIMAL(8, 2), c) FROM t;

--#[integer-types]
SELECT CAST(a AS SMALLINT), CAST(a AS INT2), CAST(a AS INTEGER), CAST(a AS INT), CAST(a AS INT4), CAST(a AS BIGINT), CAST(a AS INT8) FROM t;

--#[decimal-types]
SELECT CAST(a AS DECIMAL), CAST(a AS DECIMAL(10)), CAST(a AS DECIMAL(10, 2)), CAST(a AS NUMERIC(38, 10)) FROM t;

--#[float-types]
SELECT CAST(a AS REAL), CAST(a AS FLOAT4), CAST(a AS DOUBLE PRECISION), CAST(a AS FLOAT8), CAST(a AS FLOAT) FROM t;

--#[boolean-type]
SELECT CAST(a AS BOOLEAN), CAST(a AS BOOL) FROM t;

--#[character-types]
SELECT CAST(a AS CHAR), CAST(a AS CHAR(10)), CAST(a AS CHARACTER(10)), CAST(a AS NCHAR(10)), CAST(a AS BPCHAR) FROM t;

--#[character-varying-types]
SELECT CAST(a AS VARCHAR), CAST(a AS VARCHAR(256)), CAST(a AS CHARACTER VARYING(256)), CAST(a AS CHAR VARYING(10)), CAST(a AS NVARCHAR(10)), CAST(a AS TEXT) FROM t;

--#[character-varying-max]
SELECT CAST(a AS VARCHAR(MAX)), CAST(a AS CHARACTER VARYING(MAX)), CAST(a AS NVARCHAR(MAX)) FROM t;

--#[national-character]
SELECT CAST(a AS NATIONAL CHARACTER(10)), CAST(a AS NATIONAL CHAR(10)), CAST(a AS NATIONAL CHARACTER VARYING(10)), CAST(a AS NCHAR VARYING(10)) FROM t;

--#[datetime-types]
SELECT CAST(a AS DATE), CAST(a AS TIME), CAST(a AS TIME WITHOUT TIME ZONE), CAST(a AS TIMETZ), CAST(a AS TIME WITH TIME ZONE) FROM t;

--#[timestamp-types]
SELECT CAST(a AS TIMESTAMP), CAST(a AS TIMESTAMP WITHOUT TIME ZONE), CAST(a AS TIMESTAMPTZ), CAST(a AS TIMESTAMP WITH TIME ZONE) FROM t;

--#[interval-types]
SELECT CAST(a AS INTERVAL), CAST(a AS INTERVAL YEAR TO MONTH), CAST(a AS INTERVAL DAY TO SECOND), CAST(a AS INTERVAL SECOND(3)) FROM t;

--#[super-type]
SELECT CAST(a AS SUPER), JSON_PARSE(b)::SUPER FROM t;

--#[binary-types]
SELECT CAST(a AS VARBYTE), CAST(a AS VARBYTE(16)), CAST(a AS VARBINARY(16)), CAST(a AS BINARY VARYING(16)), CAST(a AS BINARY(4)) FROM t;

--#[other-types]
SELECT CAST(a AS GEOMETRY), CAST(a AS GEOGRAPHY), CAST(a AS HLLSKETCH) FROM t;

--#[types-case-insensitive]
SELECT CAST(a AS int), CAST(a AS Varchar(10)), a::decimal(10, 2), CAST(a AS double precision) FROM t;

--#[cast-of-expression]
SELECT CAST(a + b AS DECIMAL(10, 2)), CAST(CASE WHEN a THEN 1 ELSE 0 END AS BOOLEAN), CAST((SELECT MAX(x) FROM u) AS VARCHAR) FROM t;

--#[cast-nested]
SELECT CAST(CAST(a AS VARCHAR) AS INT), CAST(a::VARCHAR AS DATE) FROM t;
